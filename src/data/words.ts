// 모든 단어장 목록
export const allWordSets: WordSet[] = [
  beginnerWords,
  intermediateWords,
  advancedWords,
];

// 학년에 맞는 단어장 찾기
export function getWordSetsByGrade(gradeLevel: string): WordSet[] {
  return allWordSets.filter(ws => ws.gradeLevel === gradeLevel);
}

// 단어장 ID로 찾기
export function getWordSetById(id: string): WordSet | undefined {
  return allWordSets.find(ws => ws.id === id);
}

// 모든 단어장의 모든 단어를 하나의 배열로
function getAllWords() {
  return allWordSets.flatMap(ws => ws.words);
}

// 단어 ID로 단어 찾기
export function getWordById(wordId: string) {
  return getAllWords().find(w => w.id === wordId);
}

// 여러 단어 ID로 단어들 찾기
export function getWordsByIds(wordIds: string[]) {
  const allWords = getAllWords();
  return wordIds
    .map(id => allWords.find(w => w.id === id))
    .filter((w): w is NonNullable<typeof w> => w !== undefined);
}
